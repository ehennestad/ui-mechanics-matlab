classdef ListboxButton < uim.style.ButtonScheme
%ListboxButton Styling for a row in a list
%
%   Grey labels on a translucent dark fill, turning white on a
%   translucent blue fill when the row is selected. No border, so
%   adjacent rows read as one list.

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', ones(1,3) * 1, ...
            'BackgroundColor', [0.2157    0.4941    0.7216]*0.7, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'normal' )
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', ones(1,3) * 0.7, ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'normal' )
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', ones(1,3) * 1, ...
            'BackgroundColor', [0.2157    0.4941    0.7216], ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'normal' )
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', ones(1,3) * 0.7, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'normal' )
    end
end
