classdef ButtonDarkMode < uim.style.ButtonScheme
%ButtonDarkMode Button styling for dark backgrounds
%
%   Light grey labels on a translucent dark fill with a black border,
%   for toolbars sitting over dark content such as an image display.

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', ones(1,3) * 0.9, ...
            'BackgroundColor', ones(1,3) * 0.6, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'k', ...
            'BorderWidth', 0.5 )
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', ones(1,3) * 0.7, ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'k', ...
            'BorderWidth', 0.5 )
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', ones(1,3) * 0.9, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'k', ...
            'BorderWidth', 0.5 )
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', ones(1,3) * 0.7, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', 'k', ...
            'BorderWidth', 0.5 )
    end
end
