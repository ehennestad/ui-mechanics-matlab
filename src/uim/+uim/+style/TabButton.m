classdef TabButton < uim.style.ButtonScheme
%TabButton Tab styling for a dark bar, with a light selected tab
%
%   The selected tab has black labels on an opaque light grey fill.
%   Unselected tabs have light grey labels on a transparent fill, which
%   suits a dark bar such as the one uim.container.TabGroup draws.
%
%   See also uim.style.TabButtonDark, uim.style.TabButtonLight

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', ones(1,3) * 0, ...
            'BackgroundColor', ones(1,3) * 0.8, ...
            'BackgroundAlpha', 1, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.6)
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', ones(1,3) * 0.95, ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5)
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', ones(1,3) * 0, ...
            'BackgroundColor', ones(1,3) * 0.8, ...
            'BackgroundAlpha', 1, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5)
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', ones(1,3) * 0.8, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5)
    end
end
