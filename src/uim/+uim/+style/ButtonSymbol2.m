classdef ButtonSymbol2 < uim.style.ButtonScheme
%ButtonSymbol2 Icon-only button styling, duplicate of ButtonSymbol
%
%   This differs from uim.style.ButtonSymbol only in BorderWidth, and
%   both set BorderColor to 'none', so the two render identically.
%   Prefer uim.style.ButtonSymbol.

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', ones(1,3) * 1, ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...%[0.6,0.6,0.6], ...
            'BorderWidth', 1)
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', ones(1,3) * 0.85, ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...%[0.3,0.3,0.3], ...
            'BorderWidth', 1)
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', ones(1,3) * 1, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...%[0.3,0.3,0.3], ...
            'BorderWidth', 0.5)
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', ones(1,3) * 0.7, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...%[0.3,0.3,0.3], ...
            'BorderWidth', 0.5)
    end
end
