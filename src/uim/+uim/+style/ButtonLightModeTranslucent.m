classdef ButtonLightModeTranslucent < uim.style.ButtonScheme
%ButtonLightModeTranslucent Light button styling with a translucent fill
%
%   A variant of uim.style.ButtonLightMode with a partly transparent fill
%   (alpha 0.4 to 0.6), so the button reads as an overlay on whatever it
%   covers. Selected buttons have black labels on a white fill and a
%   light-blue border, so they are lighter than unselected buttons, which
%   have a grey fill; ButtonLightMode darkens the selected button
%   instead. Borders are wider: 1 when unselected and 1.5 when selected.

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', [0, 0, 0]/255, ... %ones(1,3) * 0.15
            'BackgroundColor', ones(1,3) * 0.7, ...
            'BackgroundAlpha', 0.5, ...
            'BorderColor', [122, 170, 222] ./ 255, ...
            'BorderWidth', 1.5 )
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', ones(1,3) * 0.25, ...
            'BackgroundColor', ones(1,3) * 0.95, ...
            'BackgroundAlpha', 0.5, ...
            'BorderColor', ones(1,3) * 0.5, ...
            'BorderWidth', 1 )
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', [0, 0, 0]/255, ... %ones(1,3) * 0.15
            'BackgroundColor', ones(1,3) * 1, ...
            'BackgroundAlpha', 0.6, ...
            'BorderColor', [122, 170, 222] ./ 255, ...
            'BorderWidth', 1.5 )
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', ones(1,3) * 0.4, ...
            'BackgroundColor', ones(1,3) * 0.8, ...
            'BackgroundAlpha', 0.4, ...
            'BorderColor', ones(1,3) * 0.5, ...
            'BorderWidth', 1 )
    end
end
