classdef TextLabel < uim.style.ButtonScheme
%TextLabel Text-only button styling: grey when off, blue when on
%
%   No fill and no border in any state. The label is grey when the
%   button is off, turns blue under the pointer, and is bold blue when
%   the button is on, so a row of toggle buttons reads as a list of
%   selectable words.

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', [0.2157    0.4941    0.7216], ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'bold')
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', [0.2157    0.4941    0.7216], ...
            'BackgroundColor', ones(1,3) * 0.2, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'normal')
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', [0.2157    0.4941    0.7216], ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'bold')
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', ones(1,3) * 0.4, ...
            'BackgroundColor', ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5, ...
            'FontWeight', 'normal')
    end
end
