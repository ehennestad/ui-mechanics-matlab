classdef TabButtonLight < uim.style.ButtonScheme
%TabButtonLight Tab styling that marks the selected tab with the accent colour
%
%   The selected tab takes the accent colour returned by getFocusColor
%   with a white label. Unselected tabs have dark grey labels on a
%   transparent fill and turn light grey under the pointer, so the style
%   suits a light background.
%
%   See also uim.style.TabButton, uim.style.TabButtonDark

    properties (Constant)

        % Button on with the pointer over it, or any button while pressed (see uim.style.ButtonScheme)
        HighlightedOn = struct(...
            'ForegroundColor', ones(1,3) * 1, ...
            'BackgroundColor', uim.style.TabButtonLight.getFocusColor(), ...
            'BackgroundAlpha', 0.9, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.6)
        % Button off with the pointer over it (see uim.style.ButtonScheme)
        HighlightedOff = struct(...
            'ForegroundColor', 1 - ones(1,3) * 0.95, ...
            'BackgroundColor', ones(1,3)*0.82, ...
            'BackgroundAlpha', 0.6, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5)
        % Button on (see uim.style.ButtonScheme)
        On = struct(...
            'ForegroundColor', ones(1,3) * 1, ...
            'BackgroundColor', uim.style.TabButtonLight.getFocusColor(), ...
            'BackgroundAlpha', 0.8, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5)
        % Button off (see uim.style.ButtonScheme)
        Off = struct(...
            'ForegroundColor', 1 - ones(1,3) * 0.8, ...
            'BackgroundColor', 1 - ones(1,3) * 0.4, ...
            'BackgroundAlpha', 0, ...
            'BorderColor', 'none', ...
            'BorderWidth', 0.5)
    end

    methods (Static)
        function rgb = getFocusColor
        %getFocusColor Accent colour of the selected tab
        %
        %   rgb = uim.style.TabButtonLight.getFocusColor() returns the RGB
        %   triplet [0, 0.447, 0.741] used as the selected tab fill.
            rgb = [0.0000, 0.4470, 0.7410];
        end
    end
end
