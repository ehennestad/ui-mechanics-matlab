function toolName = keyToPointerToolName(key)
%keyToPointerToolName Pointer tool bound to an unmodified key press
%
%   toolName = uim.interface.internal.keyToPointerToolName(key) returns
%   the tool key ('zoomIn', 'pan', ...) that the PointerManager toggles
%   for the keyboard key, or '' when the key has no binding.

    arguments
        key {mustBeTextScalar}
    end

    keyBindings = struct(...
        'x', 'crop', ...
        'q', 'zoomIn', ...
        'w', 'zoomOut', ...
        'y', 'pan', ...
        'i', 'dataCursor', ...
        's', 'selectObject', ...
        'd', 'polyDraw', ...
        'o', 'circleSelect', ...
        'a', 'autoDetect', ...
        't', 'freehandDraw');

    key = char(key);
    if isvarname(key) && isfield(keyBindings, key)
        toolName = keyBindings.(key);
    else
        toolName = '';
    end
end
